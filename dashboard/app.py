"""Research-only Streamlit viewer. Run: streamlit run dashboard/app.py

Never upload private patient imagery. No healthcare recommendations generated.
"""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]/'src'))
import json
import numpy as np
import streamlit as st
from PIL import Image
import torch
from onco_agent.data.datasets import image_transform
from onco_agent.models.factory import load_checkpoint
from onco_agent.models.training import choose_device
from onco_agent.tools.image_quality import quality_indicators
from onco_agent.calibration.temperature import apply_temperature
from onco_agent.agents.policy import Policy
from onco_agent.agents.learned import LearnedPolicy

st.set_page_config(page_title='ONCO-AGENT • Research Viewer', layout='wide')
st.title('ONCO-AGENT | Auditable Image Analysis')
st.error('RESEARCH DEMONSTRATION ONLY — NOT FOR CLINICAL USE. No diagnosis, triage or treatment decisions.')
st.write('This viewer classifies individual histopathology *patches* into dataset tissue categories. Do not upload private patient data.')
fast_path=st.sidebar.text_input('Fast checkpoint', value='results/models/resnet18/best.pt')
strong_path=st.sidebar.text_input('Strong checkpoint', value='results/models/efficientnet/best.pt')
config_path=st.sidebar.text_input('Frozen config', value='results/study_frozen.json')
mode=st.sidebar.selectbox('Routing policy',['rule','learned','fast','fixed_abstain'])
image_file=st.file_uploader('Upload a public research image patch',type=['png','jpg','jpeg'])

@st.cache_resource(show_spinner=False)
def resources(fast, strong):
    device=choose_device('auto')
    a, ma=load_checkpoint(fast, device)
    b, mb=load_checkpoint(strong, device)
    if ma['classes']!=mb['classes']:
        raise ValueError('Model class order mismatch')
    return a,b,ma,mb,device

if image_file is not None:
    try:
        cfg=json.loads(Path(config_path).read_text(encoding='utf-8'))
        model,strong,meta,meta2,device=resources(fast_path,strong_path)
        im=Image.open(image_file).convert('RGB')
        quality=quality_indicators(np.asarray(im.resize((64,64))))
        @torch.inference_mode()
        def do(model, shape, temperature):
            tensor=image_transform(shape)(im).unsqueeze(0).to(device)
            return apply_temperature(model(tensor).cpu().numpy(),temperature)[0]
        f=do(model,meta['size'],cfg['calibration']['fast_temperature'])
        invoked=[]
        def tool():
            invoked.append('strong_predict')
            return do(strong,meta2['size'],cfg['calibration']['strong_temperature'])
        if mode == 'learned':
            agent=LearnedPolicy.load(cfg['learned_policy_file'])
            trace=agent.run(f,tool,quality={'brightness':quality['mean_brightness'],
                'edge_variance':quality['edge_variance'],'saturation':quality['saturation_fraction']})
        else:
            agent=Policy(mode,cfg['fast_threshold'],cfg['review_threshold'])
            trace=agent.run(f,tool,quality_flag=quality['edge_variance']<cfg['blur_edge_threshold'])
        c1,c2=st.columns([1,2]);c1.image(im,caption='Single research patch',use_container_width=True)
        with c2:
            st.subheader('Technical results')
            st.write('Decision:', 'REVIEW / ABSTAIN' if trace.abstained else meta['classes'][trace.predicted_class])
            st.write('Actions:', ' → '.join(trace.actions))
            st.write('Fast model scores (not clinical probabilities):')
            st.bar_chart({meta['classes'][i]:float(f[i]) for i in range(len(f))})
            if invoked:
                st.info('Additional strong-model analysis requested by the policy.')
            st.json({'quality_indicators':quality,'strong_tool_calls':trace.strong_tool_calls,
                     'reason':trace.reason})
        st.caption('These outputs are not medically validated; quality flags are simple image statistics.')
    except Exception as exc:
        st.error(f'Cannot run inference: {exc}. Train both models and freeze a configuration first.')

st.divider()
metrics_path=st.sidebar.text_input('Optional benchmark metrics JSON',value='results/study/external_metrics.json')
if Path(metrics_path).is_file():
    metrics=json.loads(Path(metrics_path).read_text(encoding='utf-8'))
    st.subheader('Recorded experimental results')
    st.caption('Values are read from local evaluation artifacts, not generated by an LLM.')
    for key in ['fast','strong','fixed_abstain','rule','learned']:
        if key in metrics:
            st.write(key,metrics[key])
